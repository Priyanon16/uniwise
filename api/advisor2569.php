// =========================================================
// Helper: ทำความสะอาดข้อความชื่อ
// =========================================================

function normalizeText(string $text): string
{
    $text = trim($text);

    // จัดช่องว่างซ้ำ
    $text = preg_replace('/\s+/u', ' ', $text);

    return $text ?? '';
}


// =========================================================
// Helper: ทำความสะอาดคำค้นชื่ออาจารย์
//
// ตัดคำนำหน้าที่ผู้ใช้อาจพิมพ์มา เช่น
// อาจารย์, อ., ดร., ผศ., รศ.
// =========================================================

function normalizeAdvisorSearch(string $text): string
{
    $text = normalizeText($text);

    $prefixes = [
        'ผู้ช่วยศาสตราจารย์',
        'รองศาสตราจารย์',
        'ศาสตราจารย์',
        'อาจารย์',
        'ผศ.',
        'รศ.',
        'ศ.',
        'ดร.',
        'อ.'
    ];

    foreach ($prefixes as $prefix) {
        $text = str_replace($prefix, '', $text);
    }

    return normalizeText($text);
}


